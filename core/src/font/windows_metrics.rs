//! Timffle: the widths Flash Player on Windows gives device-font text.
//!
//! Flash Player lays device text out with GDI: every glyph advances by a whole
//! number of pixels, and that number is the font's *hinted* advance at the text's
//! pixel size (the `hdmx` device-metrics record when the font has one for that
//! size, otherwise the advance its hinting program produces), never the linear
//! advance the browser's canvas measures. Device fonts are not kerned. Those
//! widths were surveyed in Flash Player 32 on Windows 11 for 53 font names, 5
//! sizes and 12 scripts (`timffle-work/fontsurvey`), and this module reproduces
//! them from a bundled table so that text wraps and lines up the same on every
//! platform, whatever font actually draws the glyphs.
//!
//! What Windows Flash does, as measured:
//!
//! * A font is found by its English family name only. Localized names (宋体,
//!   新細明體, 微軟正黑體, 標楷體, …) are *not* resolved, even on a Chinese
//!   Windows: they render exactly like a made-up name.
//! * A name Windows has no font for (and the generic `_serif`) uses Times New
//!   Roman for Latin, Greek and Cyrillic glyphs; `_sans` is Arial,
//!   `_typewriter` is Courier New; `Helvetica`, `Times` and `Courier` are
//!   aliases of those three.
//! * Ideographs are always 1 em wide. Japanese kana and full-width forms that
//!   the font lacks come from MS PGothic (proportional); Thai comes from Segoe
//!   UI.
//! * Bold text in a font without a bold face is emboldened synthetically, and
//!   every glyph advances exactly one more pixel.
//!
//! The table ([`windows_metrics.bin.z`](windows_metrics.bin.z), zlib) holds,
//! per face, the linear advance of each glyph in font units plus, for pixel
//! sizes 6 to 48, the hinted advance wherever it differs from the rounded
//! linear one. It is generated by `fontsurvey/gen_metrics.py` from the fonts'
//! `hdmx` tables, FreeType's v35 interpreter (which reproduces GDI) and the
//! survey itself. Only advance widths are stored, no outlines.

use crate::font::FontDescriptor;
use crate::string::WStr;
use std::collections::HashMap;
use std::sync::OnceLock;
use std::sync::atomic::{AtomicBool, Ordering};
use swf::Twips;

/// Whether device text is laid out with these widths at all. The web player
/// turns it on; the test runner and desktop keep the renderer's own widths.
static ENABLED: AtomicBool = AtomicBool::new(false);

/// Lay device text out with Windows Flash's widths (web player).
pub fn set_enabled(enabled: bool) {
    ENABLED.store(enabled, Ordering::Relaxed);
}

static TABLE_Z: &[u8] = include_bytes!("windows_metrics.bin.z");

/// Smallest pixel size with hinted advances in the table.
const MIN_PPEM: u32 = 6;
/// Largest pixel size with measured advances in the table (Flash was surveyed
/// up to 255 px; TextFormat.size has no cap there).
const MAX_PPEM: u32 = 255;

/// The family Windows Flash uses for a name it has no font for.
pub const MISSING_FAMILY: &str = "times new roman";
/// The family whose kana and full-width forms stand in for fonts lacking them.
const JAPANESE_FALLBACK: &str = "ms pgothic";
/// Fonts with a Windows font-link entry (zh-TW Windows: MingLiU first), whose
/// kana and full-width forms are therefore 1 em, like PMingLiU's.
const LINKED_TO_MINGLIU: &[&str] = &["tahoma", "microsoft sans serif", "lucida sans unicode"];
const LINKED_JAPANESE_FALLBACK: &str = "pmingliu";
/// Traditional-Chinese fonts whose kana Windows takes from MS PGothic (font
/// link) even though the fonts have kana of their own.
const KANA_FROM_PGOTHIC: &[&str] = &[
    "microsoft jhenghei",
    "microsoft jhenghei ui",
    "pmingliu",
    "mingliu",
    "mingliu_hkscs",
    "dfkai-sb",
];
/// The family whose Thai glyphs stand in for fonts lacking them.
const THAI_FALLBACK: &str = "leelawadee ui";
/// The family whose Greek and Cyrillic glyphs stand in for fonts lacking them
/// (DFKai-SB, Microsoft JhengHei).
const GREEK_CYRILLIC_FALLBACK: &str = "arial";

/// Windows' bitmap font Courier (`coure.fon`): GDI cannot mix glyphs of other
/// fonts into a raster font, so when a run of Courier text has a character the
/// bitmap font lacks (anything outside ASCII), Flash Player sets the *whole
/// run* (same font, size, bold and italic on one line; colour does not split
/// it) in a fallback font instead, chosen by the script of the first such
/// character, at `max(size, 13)` px (13 px is Courier's smallest strike).
/// Measured in Flash 32 (`fontsurvey/probe-courier/`): Hangul → Gulim, Thai →
/// Leelawadee UI, bopomofo → SimSun, ideographs, kana, CJK symbols, full-width
/// forms, arrows, mathematical operators and geometric shapes → MS PGothic,
/// everything else (Latin-1 and Latin Extended letters, Greek, Cyrillic,
/// Hebrew, Arabic, general punctuation, currency and letterlike symbols) →
/// Arial. Those are the choices of a freshly started player; Flash reuses
/// whichever of these fallback fonts it has already realised when a later run
/// needs a glyph that font also has (so Greek after kana comes out in MS
/// PGothic), which no deterministic table can follow — Timffle always uses the
/// fresh-player choice. The line metrics stay Courier's own.
const BITMAP_FAMILY: &str = "courier";
/// Courier's smallest bitmap strike: the fallback fonts are never set smaller.
const BITMAP_MIN_FALLBACK_PPEM: u32 = 13;
const KOREAN_FALLBACK: &str = "gulim";
const BOPOMOFO_FALLBACK: &str = "simsun";

/// The font a whole run of bitmap-Courier text is set in instead (see
/// [`BITMAP_FAMILY`]).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct RunFallback {
    family: &'static str,
    ppem: u32,
}

/// The fallback family for a run of bitmap Courier whose first non-ASCII
/// character is `c`.
fn bitmap_fallback_family(c: char) -> &'static str {
    let cp = u32::from(c);
    if is_hangul(c) {
        KOREAN_FALLBACK
    } else if is_thai(c) {
        THAI_FALLBACK
    } else if matches!(cp, 0x3100..=0x312F | 0x31A0..=0x31BF) {
        BOPOMOFO_FALLBACK
    } else if is_ideograph(c)
        || is_japanese_or_fullwidth(c)
        || matches!(cp, 0x2190..=0x2BFF | 0x2E80..=0x2FFF | 0x3190..=0x319F | 0xAC00..=0xD7AF)
    {
        JAPANESE_FALLBACK
    } else {
        GREEK_CYRILLIC_FALLBACK
    }
}

/// Which browser font family should draw the glyphs of a Windows font the
/// browser does not have (the widths come from the table either way).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Substitute {
    Sans,
    Serif,
    Mono,
    /// A Chinese/Japanese/Korean font with sans-serif Latin glyphs.
    CjkSans,
    /// A Chinese/Japanese/Korean font with serif Latin glyphs.
    CjkSerif,
}

/// What a font name Flash content asked for means on Windows.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Resolution {
    /// A Windows font in the table, by its lower-case English family name.
    Known(&'static str),
    /// Not a Windows font: Flash falls back to [`MISSING_FAMILY`].
    Missing,
}

impl Resolution {
    /// The table family to take widths and line metrics from.
    pub fn family(self) -> &'static str {
        match self {
            Resolution::Known(name) => name,
            Resolution::Missing => MISSING_FAMILY,
        }
    }
}

struct Face {
    name: String,
    bold: bool,
    italic: bool,
    /// A face Windows synthesizes from `base` (GDI emboldening and/or
    /// slanting): its `deltas` hold only the measured advances that differ
    /// from the base face's hinted advance (plus one pixel when bold).
    synthetic: bool,
    base: Option<u16>,
    substitute: Substitute,
    units_per_em: u32,
    /// Sorted code points (BMP).
    code_points: Vec<u16>,
    /// Linear advance in font units, parallel to `code_points` (0 when
    /// unknown: a face built from measurements only, Windows' bitmap Courier).
    linear: Vec<u16>,
    /// `(ppem, sorted (glyph index, hinted advance in pixels))`.
    deltas: Vec<(u8, Vec<(u16, u16)>)>,
    /// OS/2 `usWinAscent`/`usWinDescent` in font units: GDI's line metrics at
    /// sizes outside [`MIN_PPEM`]..=[`MAX_PPEM`].
    win_ascent: u32,
    win_descent: u32,
    /// GDI's ascent and descent in pixels for ppem [`MIN_PPEM`]..=[`MAX_PPEM`]
    /// (the font's `VDMX` record, else the rounded `usWin` values).
    lines: Vec<(u16, u16)>,
    /// The measured width of a Hangul syllable per ppem (0 = unknown, use 1 em):
    /// font-linked fonts (Tahoma, MS Gothic, …) scale the linked Korean font.
    hangul: Vec<u16>,
    /// The same for bold text when the family has no bold face (GDI's
    /// emboldened fallback), and the line metrics of that emboldened text.
    hangul_bold: Vec<u16>,
    lines_bold: Vec<(u16, u16)>,
    /// The measured width of the face's kana and ideographs per ppem when they
    /// all share one (0 = unknown, use the rules): monospace CJK fonts are twice
    /// their half width (odd sizes round up), font-linked fonts scale the linked
    /// font, and GDI's emboldening does not always add exactly one pixel.
    cjk: Vec<u16>,
    /// The same for bold text when the family has no bold face.
    cjk_bold: Vec<u16>,
    /// The measured width of the face's kana and full-width forms per ppem when
    /// they all share one (0 = unknown): font-linked fonts (Tahoma, …) scale
    /// the linked font, so 11 px text gets 12 px glyphs.
    fw: Vec<u16>,
    fw_bold: Vec<u16>,
}

impl Face {
    fn is_cjk(&self) -> bool {
        matches!(self.substitute, Substitute::CjkSans | Substitute::CjkSerif)
    }

    /// Weight 900 and up: GDI does not embolden it further for bold text.
    fn is_heavy(&self) -> bool {
        self.name == "arial black"
    }

    fn index_of(&self, c: char) -> Option<usize> {
        let cp = u16::try_from(u32::from(c)).ok()?;
        self.code_points.binary_search(&cp).ok()
    }

    /// The stored (hinted or measured) advance of glyph `index` at `ppem`.
    fn delta(&self, index: usize, ppem: u32) -> Option<u32> {
        if (MIN_PPEM..=MAX_PPEM).contains(&ppem)
            && let Ok(at) = self.deltas.binary_search_by_key(&(ppem as u8), |(p, _)| *p)
            && let Ok(d) = self.deltas[at]
                .1
                .binary_search_by_key(&(index as u16), |(i, _)| *i)
        {
            return Some(u32::from(self.deltas[at].1[d].1));
        }
        None
    }

    /// The measured Hangul width at `ppem`, when the survey has one
    /// (`synthetic_bold`: for emboldened text of a family without a bold face).
    fn hangul(&self, ppem: u32, synthetic_bold: bool) -> Option<u32> {
        let table = if synthetic_bold {
            &self.hangul_bold
        } else {
            &self.hangul
        };
        if (MIN_PPEM..=MAX_PPEM).contains(&ppem)
            && let Some(&w) = table.get((ppem - MIN_PPEM) as usize)
            && w != 0
        {
            return Some(u32::from(w));
        }
        None
    }

    /// The uniform measured width of the face's ideographs (`c` an ideograph)
    /// or kana/full-width forms (any other `c`) at `ppem`, when the survey found
    /// one (`synthetic_bold`: emboldened text of a family without a bold face).
    fn uniform(&self, c: char, ppem: u32, synthetic_bold: bool) -> Option<u32> {
        let table = match (is_ideograph(c), synthetic_bold) {
            (true, false) => &self.cjk,
            (true, true) => &self.cjk_bold,
            (false, false) => &self.fw,
            (false, true) => &self.fw_bold,
        };
        if (MIN_PPEM..=MAX_PPEM).contains(&ppem)
            && let Some(&w) = table.get((ppem - MIN_PPEM) as usize)
            && w != 0
        {
            return Some(u32::from(w));
        }
        None
    }

    /// The advance of `c` at `ppem` pixels per em, if the face has the glyph.
    fn advance(&self, c: char, ppem: u32) -> Option<u32> {
        let index = self.index_of(c)?;
        if let Some(advance) = self.delta(index, ppem) {
            return Some(advance);
        }
        if self.linear[index] == 0xFFFF {
            // Surveyed-only glyph (no font file, or a glyph the font lacks):
            // nothing known at this size.
            return None;
        }
        Some(round_half_up(
            u32::from(self.linear[index]),
            ppem,
            self.units_per_em,
        ))
    }

    /// GDI's ascent and descent in pixels at `ppem` (`None` when unknown: a
    /// measured-only face at a size the survey did not reach).
    fn line_metrics(&self, ppem: u32, synthetic_bold: bool) -> Option<(u32, u32)> {
        if synthetic_bold
            && (MIN_PPEM..=MAX_PPEM).contains(&ppem)
            && let Some(&(a, d)) = self.lines_bold.get((ppem - MIN_PPEM) as usize)
            && (a, d) != (0, 0)
        {
            return Some((u32::from(a), u32::from(d)));
        }
        if (MIN_PPEM..=MAX_PPEM).contains(&ppem)
            && let Some(&(a, d)) = self.lines.get((ppem - MIN_PPEM) as usize)
            && (a, d) != (0, 0)
        {
            return Some((u32::from(a), u32::from(d)));
        }
        if self.win_ascent == 0 && self.win_descent == 0 {
            return None;
        }
        Some((
            round_half_up(self.win_ascent, ppem, self.units_per_em),
            round_half_up(self.win_descent, ppem, self.units_per_em),
        ))
    }
}

fn round_half_up(units: u32, ppem: u32, upm: u32) -> u32 {
    (units * ppem * 2 + upm) / (2 * upm)
}

pub struct Table {
    faces: Vec<Face>,
    by_family: HashMap<String, Vec<usize>>,
}

/// The decoded table (decoded on first use).
pub fn table() -> &'static Table {
    static TABLE: OnceLock<Table> = OnceLock::new();
    TABLE.get_or_init(|| {
        Table::decode(TABLE_Z).unwrap_or_else(|e| {
            tracing::error!("Windows font metrics table is unreadable: {e}");
            Table {
                faces: Vec::new(),
                by_family: HashMap::new(),
            }
        })
    })
}

impl Table {
    fn decode(compressed: &[u8]) -> Result<Self, String> {
        use std::io::Read;
        let mut data = Vec::new();
        flate2::read::ZlibDecoder::new(compressed)
            .read_to_end(&mut data)
            .map_err(|e| e.to_string())?;
        let mut r = Reader {
            data: &data,
            pos: 0,
        };
        if r.bytes(4)? != b"TFWM" || r.u8()? != 5 {
            return Err("bad header".into());
        }
        let count = r.u16()? as usize;
        let mut faces = Vec::with_capacity(count);
        let mut by_family: HashMap<String, Vec<usize>> = HashMap::new();
        for _ in 0..count {
            let len = r.u8()? as usize;
            let name = String::from_utf8_lossy(r.bytes(len)?).into_owned();
            let flags = r.u8()?;
            let substitute = match r.u8()? {
                0 => Substitute::Sans,
                1 => Substitute::Serif,
                2 => Substitute::Mono,
                3 => Substitute::CjkSans,
                _ => Substitute::CjkSerif,
            };
            let units_per_em = u32::from(r.u16()?);
            let min = u32::from(r.u8()?);
            let max = u32::from(r.u8()?);
            if min != MIN_PPEM || max != MAX_PPEM {
                return Err("size range mismatch".into());
            }
            let base = r.u16()?;
            let n = r.u16()? as usize;
            let code_points = (0..n).map(|_| r.u16()).collect::<Result<Vec<_>, _>>()?;
            let linear = (0..n).map(|_| r.u16()).collect::<Result<Vec<_>, _>>()?;
            let win_ascent = u32::from(r.u16()?);
            let win_descent = u32::from(r.u16()?);
            let lines = (0..=(MAX_PPEM - MIN_PPEM))
                .map(|_| Ok((r.u16()?, r.u16()?)))
                .collect::<Result<Vec<_>, String>>()?;
            let hangul = (0..=(MAX_PPEM - MIN_PPEM))
                .map(|_| r.u16())
                .collect::<Result<Vec<_>, String>>()?;
            let hangul_bold = (0..=(MAX_PPEM - MIN_PPEM))
                .map(|_| r.u16())
                .collect::<Result<Vec<_>, String>>()?;
            let lines_bold = (0..=(MAX_PPEM - MIN_PPEM))
                .map(|_| Ok((r.u16()?, r.u16()?)))
                .collect::<Result<Vec<_>, String>>()?;
            let cjk = (0..=(MAX_PPEM - MIN_PPEM))
                .map(|_| r.u16())
                .collect::<Result<Vec<_>, String>>()?;
            let cjk_bold = (0..=(MAX_PPEM - MIN_PPEM))
                .map(|_| r.u16())
                .collect::<Result<Vec<_>, String>>()?;
            let fw = (0..=(MAX_PPEM - MIN_PPEM))
                .map(|_| r.u16())
                .collect::<Result<Vec<_>, String>>()?;
            let fw_bold = (0..=(MAX_PPEM - MIN_PPEM))
                .map(|_| r.u16())
                .collect::<Result<Vec<_>, String>>()?;
            let n_ppem = r.u8()? as usize;
            let mut deltas = Vec::with_capacity(n_ppem);
            for _ in 0..n_ppem {
                let ppem = r.u8()?;
                let n_d = r.u16()? as usize;
                let list = (0..n_d)
                    .map(|_| Ok((r.u16()?, r.u16()?)))
                    .collect::<Result<Vec<_>, String>>()?;
                deltas.push((ppem, list));
            }
            by_family.entry(name.clone()).or_default().push(faces.len());
            faces.push(Face {
                name,
                bold: flags & 1 != 0,
                italic: flags & 2 != 0,
                synthetic: flags & 4 != 0,
                base: (base != 0xFFFF).then_some(base),
                substitute,
                units_per_em,
                code_points,
                linear,
                deltas,
                win_ascent,
                win_descent,
                lines,
                hangul,
                hangul_bold,
                lines_bold,
                cjk,
                cjk_bold,
                fw,
                fw_bold,
            });
        }
        Ok(Table { faces, by_family })
    }

    /// What Windows Flash makes of a font name from the content (any case,
    /// surrounding spaces ignored).
    pub fn resolve(&self, name: &str) -> Resolution {
        let lower = name.trim().to_lowercase();
        let canonical = match lower.as_str() {
            "_sans" | "sans-serif" | "helvetica" => "arial",
            "_serif" | "serif" | "times" => "times new roman",
            "_typewriter" | "monospace" => "courier new",
            other => other,
        };
        match self.by_family.get_key_value(canonical) {
            // The key lives as long as the table (static); hand out that one.
            Some((key, _)) => Resolution::Known(leak_static(key)),
            None => Resolution::Missing,
        }
    }

    /// The face for a family and style; a style the family has no face for
    /// falls back to the regular face (with synthetic bold, see
    /// [`Self::advance`]).
    fn face(&self, family: &str, bold: bool, italic: bool) -> Option<(&Face, bool)> {
        let indices = self.by_family.get(family)?;
        let exact = indices
            .iter()
            .map(|&i| &self.faces[i])
            .find(|f| f.bold == bold && f.italic == italic);
        if let Some(face) = exact {
            return Some((face, false));
        }
        let same_weight = indices
            .iter()
            .map(|&i| &self.faces[i])
            .find(|f| f.bold == bold);
        if let Some(face) = same_weight {
            return Some((face, false));
        }
        let regular = indices
            .iter()
            .map(|&i| &self.faces[i])
            .find(|f| !f.bold && !f.italic)?;
        // Bold wanted, no bold face: GDI emboldens and widens by a pixel,
        // unless the face is heavier than bold already (Arial Black).
        Some((regular, bold && !regular.is_heavy()))
    }

    /// GDI's ascent and descent (pixels) for `family` at `ppem`: the face's
    /// `VDMX` device metrics, which Flash's `getLineMetrics` reports; a bold
    /// request without a bold face uses the regular face (emboldening does not
    /// change them).
    pub fn line_metrics(
        &self,
        family: &str,
        bold: bool,
        italic: bool,
        ppem: u32,
    ) -> Option<(u32, u32)> {
        let (face, synthetic_bold) = self.face(family, bold, italic)?;
        face.line_metrics(ppem, synthetic_bold)
    }

    /// The table face a device font resolves to, for [`line_metrics_for`];
    /// `None` when the switch is off.
    pub fn face_handle(descriptor: &FontDescriptor) -> Option<FaceHandle> {
        if !ENABLED.load(Ordering::Relaxed) {
            return None;
        }
        let table = table();
        let family = table.resolve(descriptor.name()).family();
        let (face, synthetic_bold) = table.face(family, descriptor.bold(), descriptor.italic())?;
        let index = table.faces.iter().position(|f| std::ptr::eq(f, face))?;
        Some(FaceHandle(
            index as u16 | if synthetic_bold { 0x8000 } else { 0 },
        ))
    }

    /// Which browser family should draw a Windows font the browser lacks.
    pub fn substitute(&self, family: &str) -> Substitute {
        self.face(family, false, false)
            .map(|(f, _)| f.substitute)
            .unwrap_or(Substitute::Serif)
    }

    /// The advance Windows Flash gives `c` in `family` (a table family, see
    /// [`Self::resolve`]) at `ppem` pixels, or `None` when neither the font nor
    /// Flash's fallbacks for that script are covered.
    pub fn advance(
        &self,
        family: &str,
        bold: bool,
        italic: bool,
        c: char,
        ppem: u32,
    ) -> Option<u32> {
        let (face, synthetic_bold) = self.face(family, bold, italic)?;
        if bold && italic && !(face.bold && face.italic) {
            // Bold italic without a measured bold italic face, of a family
            // whose italic (or bold) Windows synthesizes: GDI applies both,
            // and the width is the bold width plus what slanting changes
            // (MS PGothic's kana in a Courier run: the slanted width plus the
            // emboldening pixel, 250 of 250 surveyed rows).
            if let Some(indices) = self.by_family.get(family)
                && indices
                    .iter()
                    .any(|&i| !self.faces[i].bold && self.faces[i].italic)
                && let Some(wb) = self.advance(family, true, false, c, ppem)
                && let Some(wi) = self.advance(family, false, true, c, ppem)
                && let Some(wr) = self.advance(family, false, false, c, ppem)
            {
                return Some((wb + wi).saturating_sub(wr));
            }
        }
        if is_hangul(c) {
            // The measured width of the (linked) Korean font at this size when
            // the survey has one, else 1 em like the ideographs.
            // The linked Korean font is emboldened for any bold request the
            // family itself cannot serve (Arial Black included).
            let emboldened = bold && !face.bold;
            if emboldened && let Some(w) = face.hangul(ppem, true) {
                return Some(w);
            }
            if let Some(w) = face.hangul(ppem, false) {
                return Some(w + u32::from(emboldened));
            }
            if face.synthetic
                && let Some(base) = self.faces.get(usize::from(face.base?))
            {
                let emboldened = face.bold && !base.bold;
                if emboldened && let Some(w) = base.hangul(ppem, true) {
                    return Some(w);
                }
                if let Some(w) = base.hangul(ppem, false) {
                    return Some(w + u32::from(emboldened));
                }
            }
        }
        if (is_ideograph(c) || is_japanese_or_fullwidth(c))
            && !(is_kana(c) && KANA_FROM_PGOTHIC.contains(&family))
        {
            // The measured width of this very glyph at this size first, then
            // the face's uniform width for its kind at this size (see
            // `Face::uniform`). The Traditional-Chinese fonts' kana are MS
            // PGothic's (proportional), decided in `advance_in`, not uniform.
            if let Some(index) = face.index_of(c)
                && let Some(advance) = face.delta(index, ppem)
            {
                return Some(advance + u32::from(synthetic_bold));
            }
            if let Some(w) = face.uniform(c, ppem, bold && !face.bold) {
                return Some(w);
            }
            if face.synthetic
                && let Some(b) = face.base
                && let Some(base) = self.faces.get(usize::from(b))
                && let Some(w) = base.uniform(c, ppem, face.bold && !base.bold)
            {
                return Some(w);
            }
        }
        if is_ideograph(c) || is_hangul(c) {
            // Ideographs and Hangul are 1 em in every font (Korean fonts' own
            // Hangul included); a pixel more when emboldened synthetically,
            // which the CJK font standing in for a Latin font always is. A
            // synthetic face (GDI's slanted bold italic of Microsoft JhengHei)
            // has its base's glyphs: a real bold CJK base is not widened.
            let real = if face.synthetic {
                face.base.and_then(|b| self.faces.get(usize::from(b)))
            } else {
                None
            }
            .unwrap_or(face);
            let real_cjk_bold = real.bold && !real.synthetic && real.is_cjk();
            return Some(ppem + u32::from(bold && !real_cjk_bold));
        }
        if face.synthetic {
            // GDI's emboldening/slanting of the base face: the measured
            // exceptions, else the base's hinted advance (plus one when bold).
            if let Some(index) = face.index_of(c)
                && let Some(advance) = face.delta(index, ppem)
            {
                return Some(advance);
            }
            let base = self.faces.get(usize::from(face.base?))?;
            let extra = face.bold && !base.bold && !base.is_heavy();
            return self.advance_in(family, base, extra, bold, c, ppem);
        }
        self.advance_in(family, face, synthetic_bold, bold, c, ppem)
    }

    /// `advance` for a concrete face; `synthetic_bold` adds the emboldening
    /// pixel to the face's own glyphs, `bold` (the text's weight) decides how
    /// the fallback fonts are emboldened — Arial Black's own glyphs are not
    /// widened for bold text, the kana MS PGothic lends it still are.
    fn advance_in(
        &self,
        family: &str,
        face: &Face,
        synthetic_bold: bool,
        bold: bool,
        c: char,
        ppem: u32,
    ) -> Option<u32> {
        // A measured width for this very glyph and size beats every rule below
        // (surveyed fallback glyphs the font itself lacks, Leelawadee's Greek…).
        // A zero-advance glyph (a combining mark) stays zero when emboldened.
        let embolden = |advance: u32| advance + u32::from(synthetic_bold && advance != 0);
        if let Some(index) = face.index_of(c)
            && let Some(advance) = face.delta(index, ppem)
        {
            if is_thai(c) && bold && face.linear[index] == 0xFFFF {
                // Thai the font lacks, in bold text: Leelawadee UI's real bold
                // face, not the surveyed regular width plus the emboldening
                // pixel (MingLiU bold italic, whose base holds regular rows).
                let (leelawadee, _) = self.face(THAI_FALLBACK, true, false)?;
                return leelawadee.advance(c, ppem);
            }
            return Some(embolden(advance));
        }
        if is_kana(c) && KANA_FROM_PGOTHIC.contains(&family) {
            let (pgothic, _) = self.face(JAPANESE_FALLBACK, false, false)?;
            return pgothic.advance(c, ppem).map(|a| a + u32::from(bold));
        }
        if let Some(advance) = face.advance(c, ppem) {
            return Some(embolden(advance));
        }
        // Scripts the font lacks: Flash's Windows fallbacks, emboldened
        // synthetically when the text is bold (neither has a bold face).
        let fallback = if is_japanese_or_fullwidth(c) {
            if LINKED_TO_MINGLIU.contains(&family) {
                LINKED_JAPANESE_FALLBACK
            } else {
                JAPANESE_FALLBACK
            }
        } else if is_thai(c) {
            // Thai in bold text comes from Leelawadee UI's real bold face.
            let (leelawadee, _) = self.face(THAI_FALLBACK, bold, false)?;
            return leelawadee.advance(c, ppem);
        } else if is_greek_or_cyrillic(c) && family == "leelawadee ui" {
            // Windows links Leelawadee UI's missing Greek and Cyrillic to a 1 em font.
            return Some(ppem + u32::from(bold));
        } else if is_greek_or_cyrillic(c) {
            GREEK_CYRILLIC_FALLBACK
        } else if face.is_cjk() && u32::from(c) < 0x3000 {
            // A Latin-1 letter or symbol missing from a GB2312 font (SimHei,
            // KaiTi, FangSong): Flash draws a full-width glyph.
            return Some(ppem + u32::from(synthetic_bold));
        } else {
            return None;
        };
        let (face, _) = self.face(fallback, false, false)?;
        face.advance(c, ppem).map(|a| a + u32::from(bold))
    }
}

/// A face of the table, small enough to travel inside `FontMetrics`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FaceHandle(u16);

/// GDI's ascent and descent at `height` (whole pixels, as Twips) for the face.
pub fn line_metrics_for(handle: FaceHandle, height: Twips) -> Option<(Twips, Twips)> {
    let ppem = height.to_pixels().round();
    if !(1.0..=4096.0).contains(&ppem) {
        return None;
    }
    let face = table().faces.get(usize::from(handle.0 & 0x7FFF))?;
    let (a, d) = face.line_metrics(ppem as u32, handle.0 & 0x8000 != 0)?;
    Some((
        Twips::from_pixels(f64::from(a)),
        Twips::from_pixels(f64::from(d)),
    ))
}

fn leak_static(key: &str) -> &'static str {
    // Keys of the global table live for the whole program; the table is only
    // ever built once (see `table()`).
    // SAFETY-free alternative to unsafe lifetime extension: intern the names.
    static NAMES: OnceLock<std::sync::Mutex<HashMap<String, &'static str>>> = OnceLock::new();
    let names = NAMES.get_or_init(Default::default);
    let mut names = names.lock().unwrap_or_else(|e| e.into_inner());
    if let Some(s) = names.get(key) {
        return s;
    }
    let s: &'static str = Box::leak(key.to_owned().into_boxed_str());
    names.insert(key.to_owned(), s);
    s
}

/// CJK unified ideographs and compatibility ideographs: 1 em in every font.
fn is_ideograph(c: char) -> bool {
    matches!(u32::from(c),
        0x3400..=0x4DBF | 0x4E00..=0x9FFF | 0xF900..=0xFAFF | 0x20000..=0x3134F)
}

/// Kana, CJK symbols/punctuation, bopomofo and half/full-width forms.
fn is_japanese_or_fullwidth(c: char) -> bool {
    matches!(u32::from(c), 0x3000..=0x30FF | 0x3100..=0x312F | 0x31A0..=0x31BF | 0x3200..=0x33FF | 0xFE30..=0xFE4F | 0xFF00..=0xFFEF)
}

fn is_thai(c: char) -> bool {
    matches!(u32::from(c), 0x0E00..=0x0E7F)
}

fn is_kana(c: char) -> bool {
    matches!(u32::from(c), 0x3040..=0x30FF)
}

fn is_hangul(c: char) -> bool {
    matches!(u32::from(c), 0x1100..=0x11FF | 0x3130..=0x318F | 0xAC00..=0xD7A3)
}

fn is_greek_or_cyrillic(c: char) -> bool {
    matches!(u32::from(c), 0x0370..=0x03FF | 0x0400..=0x04FF)
}

/// The advance Windows Flash gives `c` in the device font `descriptor` at
/// `height` (the font size), rounded to whole pixels, or `None` when the
/// table does not know; sizes are whole pixels in Flash.
pub fn device_advance(descriptor: &FontDescriptor, c: char, height: Twips) -> Option<Twips> {
    if !ENABLED.load(Ordering::Relaxed) {
        return None;
    }
    lookup_device_advance(descriptor, c, height)
}

/// [`device_advance`] without the enable switch.
fn lookup_device_advance(descriptor: &FontDescriptor, c: char, height: Twips) -> Option<Twips> {
    let ppem = height.to_pixels().round();
    if !(1.0..=4096.0).contains(&ppem) {
        return None;
    }
    let table = table();
    let family = table.resolve(descriptor.name()).family();
    table
        .advance(
            family,
            descriptor.bold(),
            descriptor.italic(),
            c,
            ppem as u32,
        )
        .map(|px| Twips::from_pixels(f64::from(px)))
}

/// Whether `descriptor` names Windows' bitmap Courier, whose text is laid out
/// run by run (see [`run_fallback`]); `false` when the switch is off.
pub fn is_bitmap_font(descriptor: &FontDescriptor) -> bool {
    ENABLED.load(Ordering::Relaxed) && table().resolve(descriptor.name()).family() == BITMAP_FAMILY
}

/// The font Windows Flash sets a whole run of device text in instead of the
/// requested one: bitmap Courier with a character outside ASCII in the run
/// (see [`BITMAP_FAMILY`]). `None` for every other font, or when the run is
/// plain ASCII, or when the switch is off.
pub fn run_fallback(
    descriptor: &FontDescriptor,
    text: &WStr,
    height: Twips,
) -> Option<RunFallback> {
    if !ENABLED.load(Ordering::Relaxed) {
        return None;
    }
    lookup_run_fallback(descriptor, text, height)
}

/// [`run_fallback`] without the enable switch.
fn lookup_run_fallback(
    descriptor: &FontDescriptor,
    text: &WStr,
    height: Twips,
) -> Option<RunFallback> {
    let table = table();
    if table.resolve(descriptor.name()).family() != BITMAP_FAMILY {
        return None;
    }
    let ppem = height.to_pixels().round();
    if !(1.0..=4096.0).contains(&ppem) {
        return None;
    }
    let first = text
        .chars()
        .map(|c| c.unwrap_or(char::REPLACEMENT_CHARACTER))
        .find(|&c| u32::from(c) >= 0x80)?;
    Some(RunFallback {
        family: bitmap_fallback_family(first),
        ppem: (ppem as u32).max(BITMAP_MIN_FALLBACK_PPEM),
    })
}

/// [`device_advance`] for a glyph of a run that Windows Flash set in `run`'s
/// fallback font (every glyph of the run, ASCII included, takes that font's
/// width at the run's size); without a run fallback, the glyph's own font.
pub fn device_advance_in(
    descriptor: &FontDescriptor,
    c: char,
    height: Twips,
    run: Option<RunFallback>,
) -> Option<Twips> {
    let Some(run) = run else {
        return device_advance(descriptor, c, height);
    };
    if !ENABLED.load(Ordering::Relaxed) {
        return None;
    }
    table()
        .advance(
            run.family,
            descriptor.bold(),
            descriptor.italic(),
            c,
            run.ppem,
        )
        .map(|px| Twips::from_pixels(f64::from(px)))
}

struct Reader<'a> {
    data: &'a [u8],
    pos: usize,
}

impl Reader<'_> {
    fn bytes(&mut self, n: usize) -> Result<&[u8], String> {
        let end = self.pos.checked_add(n).ok_or("overflow")?;
        let slice = self.data.get(self.pos..end).ok_or("truncated")?;
        self.pos = end;
        Ok(slice)
    }
    fn u8(&mut self) -> Result<u8, String> {
        Ok(self.bytes(1)?[0])
    }
    fn u16(&mut self) -> Result<u16, String> {
        let b = self.bytes(2)?;
        Ok(u16::from_le_bytes([b[0], b[1]]))
    }
}

